"""Merge the combat helper learning players shared into the addon (Advisor/CombatShared.lua).

The app posts anonymous summaries to the private #combat-data channel (app/flipforever/share.py).
Before a release, copy that channel's text into a file in tools/combat_inbox/ (any name, .txt):
this script reads every summary in there, keeps the newest one per install and spell order, adds
them up per class/build/level band, stores the result in tools/combat_shared.json (only these sums,
no install IDs) and writes the addon file. Without new inbox files it just rewrites the addon file
from tools/combat_shared.json, which build_release.py does on every build.

    python tools/merge_combat_learning.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INBOX = ROOT / "tools" / "combat_inbox"
STORE = ROOT / "tools" / "combat_shared.json"
SEEN = ROOT / "tools" / "combat_inbox" / "merged.json"      # newest summary per install (not committed)
OUT = ROOT / "addon" / "FlipForever" / "Advisor" / "CombatShared.lua"
FIELDS = ("n", "kills", "time", "deaths", "hp")
KEY_RE = re.compile(r"^[A-Z]+:[A-Za-z0-9_]+:[0-9a-z\-]+$")
NAME_RE = re.compile(r"^[A-Za-z0-9 :'\-()]+$")
LIMIT = {"n": 500, "kills": 500, "time": 50000, "deaths": 500, "hp": 500}   # one install's numbers can't be larger


def parse(text: str) -> list[dict]:
    """Every summary in a dump of the channel (```json blocks or bare objects)."""
    out = []
    for m in re.finditer(r'\{"f":1,.*?\}\}\}', text, re.S):
        try:
            d = json.loads(m.group(0))
        except ValueError:
            continue
        if valid(d):
            out.append(d)
    return out


def valid(d: dict) -> bool:
    """Only well-formed summaries with sane numbers count (the channel is write-only, but be safe)."""
    if not (isinstance(d, dict) and d.get("f") == 1 and isinstance(d.get("i"), str) and len(d["i"]) <= 32):
        return False
    if not (isinstance(d.get("k"), str) and KEY_RE.match(d["k"]) and isinstance(d.get("s"), str)):
        return False
    if not all(NAME_RE.match(p) for p in d["s"].split(">")):
        return False
    vs = d.get("v")
    if not isinstance(vs, dict) or not vs or len(vs) > 8:
        return False
    for name, v in vs.items():
        if not (isinstance(name, str) and len(name) <= 60 and isinstance(v, dict)):
            return False
        for f in FIELDS:
            x = v.get(f, 0)
            if not isinstance(x, (int, float)) or x < 0 or x > LIMIT[f]:
                return False
        if v.get("kills", 0) > v.get("n", 0) or v.get("deaths", 0) > v.get("n", 0):
            return False
    return True


def merge(summaries: list[dict], seen: dict) -> dict:
    """Newest summary per (install, key, order) wins; then add everything up."""
    for d in summaries:
        seen[f'{d["i"]}|{d["k"]}|{d["s"]}'] = d
    total: dict = {}
    for d in seen.values():
        slot = total.setdefault(d["k"], {}).setdefault(d["s"], {})
        for name, v in d["v"].items():
            t = slot.setdefault(name, {f: 0 for f in FIELDS})
            for f in FIELDS:
                t[f] = round(t[f] + float(v.get(f, 0)), 1)
    return total


def lua_quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def to_lua(total: dict) -> str:
    lines = [
        "-- What all players' combat helpers learned, merged from the anonymous summaries they shared.",
        "-- Generated by tools/merge_combat_learning.py when a release is built: do not edit by hand.",
        '-- FF.COMBAT_SHARED["CLASS:build:band"]["Spell>Spell>..."]["variant"] = { n, kills, time, deaths, hp }',
        "local FF = FlipForever",
        "FF.COMBAT_SHARED = {",
    ]
    for key in sorted(total):
        lines.append(f"  [{lua_quote(key)}] = {{")
        for sig in sorted(total[key]):
            lines.append(f"    [{lua_quote(sig)}] = {{")
            for name in sorted(total[key][sig]):
                v = total[key][sig][name]
                nums = ", ".join(f"{f} = {v[f]:g}" for f in FIELDS)
                lines.append(f"      [{lua_quote(name)}] = {{ {nums} }},")
            lines.append("    },")
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv=None) -> dict:
    seen = json.loads(SEEN.read_text(encoding="utf-8")) if SEEN.exists() else {}
    new = []
    if INBOX.exists():
        for f in sorted(INBOX.glob("*.txt")):
            new += parse(f.read_text(encoding="utf-8", errors="replace"))
    if new or seen:
        total = merge(new, seen)
        INBOX.mkdir(exist_ok=True)
        SEEN.write_text(json.dumps(seen, sort_keys=True), encoding="utf-8")
        STORE.write_text(json.dumps(total, indent=1, sort_keys=True), encoding="utf-8")
    else:
        total = json.loads(STORE.read_text(encoding="utf-8")) if STORE.exists() else {}
    text = to_lua(total)
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"CombatShared.lua updated ({len(total)} class/build/band entries, {len(new)} new summaries)")
    else:
        print("CombatShared.lua up to date")
    return total


if __name__ == "__main__":
    main(sys.argv[1:])
